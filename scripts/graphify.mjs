import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourceRoot = path.join(root, "src");
const outputPath = path.join(root, "docs/code-graph.md");
const sourceExtensions = new Set([".ts", ".tsx"]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(filePath);
    return sourceExtensions.has(path.extname(entry.name)) ? [filePath] : [];
  }));
  return nested.flat();
}

const files = (await walk(sourceRoot)).sort();
const knownPaths = new Set(files.map((file) => path.relative(root, file).replaceAll(path.sep, "/")));
const nodes = new Map();
const edges = [];

for (const file of files) {
  const relative = path.relative(root, file).replaceAll(path.sep, "/");
  const source = await readFile(file, "utf8");
  const id = relative.replace(/[^A-Za-z0-9_]/g, "_");
  nodes.set(id, relative);
  const imports = source.matchAll(/(?:from\s*|import\s*\()\s*["']([^"']+)["']/g);
  for (const [, specifier] of imports) {
    if (!specifier.startsWith(".") && !specifier.startsWith("@/")) continue;
    const base = specifier.startsWith("@/")
      ? `src/${specifier.slice(2)}`
      : path.posix.normalize(path.posix.join(path.posix.dirname(relative), specifier));
    const target = [base, ...[...sourceExtensions].map((extension) => base + extension), ...[...sourceExtensions].map((extension) => base + "/index" + extension)]
      .find((candidate) => knownPaths.has(candidate));
    if (target) edges.push([id, target.replace(/[^A-Za-z0-9_]/g, "_")]);
  }
}

const escapeLabel = (value) => value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
const lines = [
  "# Source dependency graph",
  "",
  "> Generated by `npm run graphify` from relative TypeScript/TSX imports in `src/`. Verify behavior in source; this graph is a navigation map, not a semantic model.",
  "",
  `Source files: ${files.length}. Internal import edges: ${edges.length}.`,
  "",
  "```mermaid",
  "flowchart LR",
  ...[...nodes].map(([id, label]) => `  ${id}[\"${escapeLabel(label)}\"]`),
  ...edges.map(([from, to]) => `  ${from} --> ${to}`),
  "```",
  "",
];

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, lines.join("\n"));
console.log(`Graph generated: ${nodes.size} files, ${edges.length} internal imports -> ${path.relative(root, outputPath)}`);
